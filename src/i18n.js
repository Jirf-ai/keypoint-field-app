export function makeT(lang) {
  const d = STRINGS[lang] ?? STRINGS.en;
  return (key) => d[key] ?? STRINGS.en[key] ?? key;
}

export function phaseLabel(code, lang) {
  const p = PHASE_LABELS[code];
  return p ? p[lang] ?? p.en : code;
}
